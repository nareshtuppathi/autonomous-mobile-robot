function row = slLogPack(pose, infoVec, cmd, velLog, clearanceM, inMap, braking, reasonCode)
%SLLOGPACK Pack one step of logged signals into a single column (order: slLogLayout).
    pose = pose(:);  cmd = cmd(:);  velLog = velLog(:);
    row = [pose(1); pose(2); pose(3); cmd(1); cmd(2); infoVec(1); infoVec(2); infoVec(3); ...
           infoVec(4); infoVec(5); infoVec(6); infoVec(7); infoVec(8); infoVec(9); infoVec(10); ...
           infoVec(11); infoVec(12); infoVec(13); infoVec(14); infoVec(15); infoVec(16); ...
           clearanceM; inMap; braking; reasonCode; velLog(1); velLog(2)];
end
